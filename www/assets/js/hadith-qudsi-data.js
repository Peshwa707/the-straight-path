// Helper functions
const HADITH_QUDSI_HELPER = {
    getAllHadith: function() {
        return HADITH_QUDSI;
    },

    getHadithByNumber: function(number) {
        return HADITH_QUDSI.find(h => h.number === number);
    },

    getHadithByTheme: function(theme) {
        return HADITH_QUDSI.filter(h => h.theme.toLowerCase().includes(theme.toLowerCase()));
    },

    searchHadith: function(searchTerm) {
        const term = searchTerm.toLowerCase();
        return HADITH_QUDSI.filter(h =>
            h.translation.toLowerCase().includes(term) ||
            h.explanation.toLowerCase().includes(term) ||
            h.theme.toLowerCase().includes(term)
        );
    },

    getTotalCount: function() {
        return HADITH_QUDSI.length;
    }
};

// Make it available globally
window.HADITH_QUDSI = HADITH_QUDSI;
window.HADITH_QUDSI_HELPER = HADITH_QUDSI_HELPER;
