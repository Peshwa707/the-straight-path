// Function to merge additional Surahs with main Quran data
if (window.QURAN_DATA) {
    ADDITIONAL_SURAHS.forEach(surah => {
        const existingIndex = window.QURAN_DATA.surahs.findIndex(s => s.number === surah.number);
        if (existingIndex === -1) {
            window.QURAN_DATA.surahs.push(surah);
        }
    });
    // Sort by Surah number
    window.QURAN_DATA.surahs.sort((a, b) => a.number - b.number);
}
